import os
import json
import requests
import re
from ..models import SessionLocal, IdeaCandidate, EngineLog, Base, engine as db_engine

class SaasFactory:
    def __init__(self):
        self.output_dir = "products"
        self.ollama_url = "http://localhost:11434/api/generate"
        self.model = "llama3"

    def ask_llm(self, prompt):
        try:
            response = requests.post(
                self.ollama_url,
                json={"model": self.model, "prompt": prompt, "stream": False},
                timeout=60
            )
            if response.status_code == 200:
                return response.json().get('response', '')
        except:
            pass
        return None

    def generate_project(self, idea):
        project_name = idea['theme'].lower().replace(' ', '-')
        project_path = os.path.join(self.output_dir, project_name)
        os.makedirs(project_path, exist_ok=True)

        # 1. Generate App.jsx logic via LLM
        prompt_ui = f"Buat kode React (JSX) untuk aplikasi SaaS bernama '{idea['theme']}'. Deskripsi: {idea['summary']}. Gunakan Tailwind CSS. Berikan kodenya saja tanpa markdown."
        app_code = self.ask_llm(prompt_ui) or f"export default function App() {{ return <div className='p-10'><h1>{idea['theme']}</h1><p>{idea['summary']}</p></div> }}"

        # 2. Generate Technical Spec
        prompt_spec = f"Berikan spesifikasi teknis JSON untuk SaaS '{idea['theme']}'. Format: {{\"features\": [], \"monetization\": \"\"}}. Deskripsi: {idea['summary']}"
        spec_raw = self.ask_llm(prompt_spec) or "{}"
        match = re.search(r'\{.*\}', spec_raw, re.DOTALL)
        spec = json.loads(match.group()) if match else {}

        # Scaffolding
        files = {
            "package.json": {
                "name": project_name,
                "version": "1.0.0",
                "scripts": {"dev": "vite", "build": "vite build"},
                "dependencies": {"react": "^18.2.0", "react-dom": "^18.2.0", "vite": "^5.0.0", "tailwindcss": "^3.0.0", "lucide-react": "^0.284.0"}
            },
            "spec.json": spec,
            "README.md": f"# {idea['theme']}\n\n{idea['summary']}\n\nGenerated by Organisme Saas Otonom.",
            "vite.config.js": "import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\nexport default defineConfig({ plugins: [react()] });",
            "tailwind.config.js": "module.exports = { content: ['./index.html', './src/**/*.{js,ts,jsx,tsx}'], theme: { extend: {} }, plugins: [] };",
            "postcss.config.js": "module.exports = { plugins: { tailwindcss: {}, autoprefixer: {}, } };",
            "index.html": f"<!DOCTYPE html><html><head><meta charset='UTF-8'/><title>{idea['theme']}</title></head><body><div id='root'></div><script type='module' src='/src/main.jsx'></script></body></html>",
            "src/main.jsx": "import React from 'react';\nimport ReactDOM from 'react-dom/client';\nimport App from './App';\nimport './index.css';\nReactDOM.createRoot(document.getElementById('root')).render(<React.StrictMode><App /></React.StrictMode>);",
            "src/App.jsx": app_code,
            "src/index.css": "@tailwind base;\n@tailwind components;\n@tailwind utilities;",
            "docker-compose.yml": f"version: '3.8'\nservices:\n  web:\n    build: .\n    ports:\n      - '8081:8080'\n",
            "Dockerfile": "FROM node:20-slim\nWORKDIR /app\nCOPY package*.json ./\nRUN npm install\nCOPY . .\nCMD [\"npm\", \"run\", \"dev\", \"--\", \"--host\", \"0.0.0.0\"]"
        }

        for file_name, content in files.items():
            full_path = os.path.join(project_path, file_name)
            os.makedirs(os.path.dirname(full_path), exist_ok=True)
            if isinstance(content, dict):
                with open(full_path, 'w') as f:
                    json.dump(content, f, indent=2)
            else:
                with open(full_path, 'w') as f:
                    f.write(content)

        return project_path

    async def run(self):
        print("\n" + "="*50)
        print("🏭 SAAS FACTORY (RAHIM) STARTING")
        print("="*50)

        Base.metadata.create_all(bind=db_engine)
        db = SessionLocal()

        try:
            idea = db.query(IdeaCandidate).order_by(IdeaCandidate.created_at.desc()).first()
            if not idea:
                return None

            print(f"   🏗️  Building AI-Generated product for: {idea.theme}")
            project_path = self.generate_project({
                "theme": idea.theme,
                "summary": idea.summary
            })

            log = EngineLog(level="success", source="FACTORY", message=f"AI-Generated product at: {project_path}")
            db.add(log)
            db.commit()
            return project_path
        except Exception as e:
            print(f"🔥 FACTORY ERROR: {e}")
            return None
        finally:
            db.close()
