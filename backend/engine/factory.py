from sqlalchemy.orm import Session
from .. import models
from .llm import llm
import os
import datetime
import json

async def run_factory(db: Session):
    log = models.EngineLog(level="info", source="Factory", message="SaaS Factory started")
    db.add(log)
    db.commit()

    # Get top unprocessed idea
    top_idea = db.query(models.IdeaCandidate).filter(models.IdeaCandidate.is_processed == False).order_by(models.IdeaCandidate.score.desc()).first()
    if not top_idea:
        db.add(models.EngineLog(level="info", source="Factory", message="No new ideas to build."))
        db.commit()
        return

    # Generate structured blueprint using LLM
    prompt = f"Generate a technical blueprint for this SaaS idea:\nIdea: {top_idea.theme}\nSummary: {top_idea.summary}\n\nProvide JSON with keys: 'schema', 'endpoints', 'frontend_components'."
    llm_output = await llm.generate(prompt, system="You are the SaaS Factory Agent.")

    try:
        # Try to extract JSON if LLM returned extra text
        import re
        json_match = re.search(r"(\{.*\})", llm_output, re.S)
        if json_match:
            details = json.loads(json_match.group(1))
        else:
            details = {"raw": llm_output}
    except:
        details = {"raw": llm_output}

    os.makedirs("products", exist_ok=True)
    product_name = top_idea.theme.lower().replace(" ", "_").replace("/", "_")
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    product_dir = f"products/{product_name}_{timestamp}"
    os.makedirs(product_dir, exist_ok=True)

    # 1. Save Blueprint JSON
    blueprint_path = f"{product_dir}/blueprint.json"
    blueprint = {
        "idea_id": top_idea.id,
        "theme": top_idea.theme,
        "summary": top_idea.summary,
        "technical_details": details,
        "generated_at": str(datetime.datetime.now())
    }
    with open(blueprint_path, "w") as f:
        json.dump(blueprint, f, indent=2)

    # 2. Generate backend/main.py (Enhanced with simple persistence)
    backend_code = f"""from fastapi import FastAPI
from pydantic import BaseModel
from typing import List
import sqlite3
import os

app = FastAPI(title="{top_idea.theme} API")

# Initialize mini-DB for the product
db_path = "product_data.db"

def init_db():
    conn = sqlite3.connect(db_path)
    conn.execute("CREATE TABLE IF NOT EXISTS leads (id INTEGER PRIMARY KEY, email TEXT, interest TEXT)")
    conn.commit()
    conn.close()

init_db()

class Lead(BaseModel):
    email: str
    interest: str

@app.get("/")
async def root():
    return {{
        "message": "Welcome to {top_idea.theme}",
        "summary": "{top_idea.summary}",
        "autonomous_id": "{timestamp}"
    }}

@app.post("/register")
async def register(lead: Lead):
    conn = sqlite3.connect(db_path)
    conn.execute("INSERT INTO leads (email, interest) VALUES (?, ?)", (lead.email, lead.interest))
    conn.commit()
    conn.close()
    return {{"status": "success", "message": "Lead captured by {product_name}"}}

@app.get("/health")
async def health():
    return {{"status": "alive", "engine": "Gen-3 SaaS Factory"}}
"""
    os.makedirs(f"{product_dir}/backend", exist_ok=True)
    with open(f"{product_dir}/backend/main.py", "w") as f:
        f.write(backend_code)

    # 3. Generate frontend/index.html (Tailwind CDN version for instant preview)
    frontend_code = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{top_idea.theme}</title>
    <script src="https://cdn.tailwindcss.com"></script>
</head>
<body class="bg-gray-50 text-gray-900 font-sans">
    <div class="max-w-4xl mx-auto px-4 py-12">
        <header class="text-center mb-12">
            <h1 class="text-4xl font-bold text-indigo-600 mb-4">{top_idea.theme}</h1>
            <p class="text-xl text-gray-600">{top_idea.summary}</p>
        </header>

        <main class="bg-white shadow-lg rounded-lg p-8">
            <h2 class="text-2xl font-semibold mb-6">Autonomous MVP Dashboard</h2>
            <div class="grid grid-cols-1 md:grid-cols-2 gap-6">
                <div class="border p-4 rounded-md">
                    <h3 class="font-bold mb-2">System Status</h3>
                    <p class="text-green-500 font-mono">● OPERATIONAL</p>
                </div>
                <div class="border p-4 rounded-md">
                    <h3 class="font-bold mb-2">Generation</h3>
                    <p class="text-indigo-500 font-mono">#0001</p>
                </div>
            </div>
            <div class="mt-8 text-center">
                <button class="bg-indigo-600 text-white px-6 py-2 rounded-full hover:bg-indigo-700 transition">
                    Get Started
                </button>
            </div>
        </main>

        <footer class="mt-12 text-center text-gray-400 text-sm">
            Generated by ORGANISME SAAS OTONOM
        </footer>
    </div>
</body>
</html>
"""
    os.makedirs(f"{product_dir}/frontend", exist_ok=True)
    with open(f"{product_dir}/frontend/index.html", "w") as f:
        f.write(frontend_code)

    # Create product record
    new_product = models.Product(
        idea_id=top_idea.id,
        name=top_idea.theme,
        blueprint_path=blueprint_path
    )
    db.add(new_product)

    # Mark idea as processed
    top_idea.is_processed = True

    db.add(models.EngineLog(level="info", source="Factory", message=f"Full product generated: {top_idea.theme}. Location: {product_dir}"))
    db.commit()
    return {"product": top_idea.theme, "path": product_dir}
